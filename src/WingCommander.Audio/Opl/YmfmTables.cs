    /// <remarks>C++: pm_scale (opl_clock_noise_and_lfo, ymfm_opl.cpp).</remarks>
    private static readonly sbyte[] PmScale = [8, 4, 0, -4, -8, -4, 0, 4];

    /// <summary>
    /// The four OPL2 waveforms (sine, half sine, absolute sine, quarter sine) as 4.8
    /// attenuation with the sign in bit 15. Identical for every chip, so they are shared.
    /// </summary>
    /// <remarks>C++: m_waveform (opl_registers_base constructor, ymfm_opl.cpp).</remarks>
    public static readonly ushort[][] Waveforms = BuildWaveforms();

    /// <remarks>C++: bitfield (ymfm.h).</remarks>
    public static uint Bitfield(uint value, int start, int length = 1) => (value >> start) & ((1u << length) - 1);

    /// <remarks>C++: clamp (ymfm.h).</remarks>
    public static int Clamp(int value, int minval, int maxval)
    {
        if (value < minval)
            return minval;
        if (value > maxval)
            return maxval;
        return value;
    }

    /// <remarks>C++: abs_sin_attenuation (ymfm_fm.ipp).</remarks>
    public static uint AbsSinAttenuation(uint input)
    {
        if (Bitfield(input, 8) != 0)
            input = ~input;
        return SinTable[input & 0xff];
    }

    /// <remarks>C++: attenuation_to_volume (ymfm_fm.ipp). 5.8 log attenuation to 13-bit linear volume.</remarks>
    public static uint AttenuationToVolume(uint input) => (uint)(PowerTable[input & 0xff] >> (int)(input >> 8));

    /// <remarks>C++: attenuation_increment (ymfm_fm.ipp).</remarks>
    public static uint AttenuationIncrement(uint rate, uint index) => Bitfield(IncrementTable[rate], (int)(4 * index), 4);

    /// <remarks>C++: opl_key_scale_atten (ymfm_opl.cpp).</remarks>
    public static uint OplKeyScaleAtten(uint block, uint fnum4Msb)
    {
        int result = FnumToAtten[fnum4Msb] - 8 * (int)(block ^ 7);
        return (uint)Math.Max(0, result);
    }

    /// <remarks>C++: pm_scale lookup of opl_clock_noise_and_lfo (ymfm_opl.cpp).</remarks>
    public static int PmScaleAt(uint index) => PmScale[index];

    /// <remarks>C++: fm_registers_base::effective_rate (ymfm_fm.h).</remarks>
    public static uint EffectiveRate(uint rawRate, uint ksr) => rawRate == 0 ? 0 : Math.Min(rawRate + ksr, 63u);

    /// <summary>
    /// Simulates the YM3014 DAC: converts to the 3.10 floating-point format and back, which
    /// zeroes the low mantissa bits that the DAC loses.
    /// </summary>
    /// <remarks>C++: roundtrip_fp (ymfm.h).</remarks>
    public static int RoundtripFp(int value)
    {
        if (value < -32768)
            return -32768;
        if (value > 32767)
            return 32767;
        int scanValue = value ^ (value >> 31);
        int exponent = 7 - BitOperations.LeadingZeroCount(unchecked((uint)scanValue << 17));
        exponent = Math.Max(exponent, 1);
        exponent -= 1;
        int mask = (1 << exponent) - 1;
        return value & ~mask;
    }

    private static ushort[] BuildPowerTable()
    {
        var table = new ushort[256];
        for (int i = 0; i < table.Length; i++)
            table[i] = (ushort)((PowerMantissas[i] | 0x400) << 2);
        return table;
    }

    private static ushort[][] BuildWaveforms()
    {
        var wf0 = new ushort[WaveformLength];
        var wf1 = new ushort[WaveformLength];
        var wf2 = new ushort[WaveformLength];
        var wf3 = new ushort[WaveformLength];
        for (uint index = 0; index < WaveformLength; index++)
            wf0[index] = (ushort)(AbsSinAttenuation(index) | (Bitfield(index, 9) << 15));

        ushort zeroValue = wf0[0];
        for (uint index = 0; index < WaveformLength; index++)
        {
            wf1[index] = Bitfield(index, 9) != 0 ? zeroValue : wf0[index];
            wf2[index] = (ushort)(wf0[index] & 0x7fff);
            wf3[index] = Bitfield(index, 8) != 0 ? zeroValue : (ushort)(wf0[index] & 0x7fff);
        }
        return [wf0, wf1, wf2, wf3];
    }
